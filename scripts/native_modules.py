def identify_native_module(sha256: str, module_name: str) -> NativeModuleIdentity:
    """Identify original or authenticated inspection bytes before selecting a flow.

    A 2026 identity joins its protected original, companion and recovered engine.
    This is provenance only; reconstructed images are static inspection artifacts,
    and matching exports do not certify compatibility with another build.
    """
    if not isinstance(sha256, str) or not isinstance(module_name, str):
        raise TypeError("Exact SHA-256 and canonical module name required")
    plain = _PLAIN2026.get(sha256)
    if plain is not None:
        canonical_name, exports = plain
        if canonical_name != module_name:
            raise ValueError("Unrecognized native module digest/name combination")
        return NativeModuleIdentity(sha256, canonical_name, "2026", ("2026",), exports)
    original_sha = _RECONSTRUCTED2026.get(sha256, sha256)
    row = _PROTECTED2026.get(original_sha)
    if row is None:
        return _identify_original_native_module(sha256, module_name)
    canonical_name, companion, engine = row
    if canonical_name != module_name:
        raise ValueError("Unrecognized native module digest/name combination")
    return NativeModuleIdentity(
        sha256,
        canonical_name,
        "2026",
        ("2026",),
        _RECOVERED2026_EXPORTS[canonical_name],
        "protected-original" if sha256 == original_sha else "reconstructed-inspection",
        engine,
        companion,
    )
